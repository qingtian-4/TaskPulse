use serde::{Deserialize, Serialize};

pub const MAX_INPUT: usize = 64 * 1024;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum Kind {
    #[serde(rename = "session.discovered")]
    Discovered,
    #[serde(rename = "session.renamed")]
    Renamed,
    #[serde(rename = "turn.started")]
    Started,
    #[serde(rename = "turn.submitted")]
    Submitted,
    #[serde(rename = "phase.changed")]
    Phase,
    #[serde(rename = "tool.started")]
    ToolStarted,
    #[serde(rename = "tool.finished")]
    ToolFinished,
    #[serde(rename = "input.requested")]
    Requested,
    #[serde(rename = "input.resolved")]
    Resolved,
    #[serde(rename = "turn.stop_requested")]
    StopRequested,
    #[serde(rename = "turn.completed")]
    Completed,
    #[serde(rename = "turn.failed")]
    Failed,
    #[serde(rename = "turn.interrupted")]
    Interrupted,
    #[serde(rename = "session.closed")]
    Closed,
    #[serde(rename = "heartbeat")]
    Heartbeat,
    #[serde(rename = "connection.test")]
    Test,
    /// A host fact whose originating turn/call cannot be proven. It may be
    /// recorded, but must never alter lifecycle, pending input or activity age.
    #[serde(rename = "observation.unassociated")]
    Unassociated,
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Payload {
    #[serde(default)]
    pub title: Option<String>,
    #[serde(default)]
    pub project: Option<String>,
    #[serde(default)]
    pub project_path: Option<String>,
    #[serde(default)]
    pub model: Option<String>,
    #[serde(default)]
    pub phase: Option<crate::domain::ExecutionPhase>,
    /// A minimal label, never raw tool inputs, prompts or outputs.
    #[serde(default)]
    pub activity: Option<String>,
    #[serde(default)]
    pub request_kind: Option<crate::domain::WaitingReason>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Event {
    pub schema_version: u8,
    pub agent_id: String,
    pub session_id: String,
    pub event_id: String,
    pub kind: Kind,
    #[serde(default)]
    pub turn_id: Option<String>,
    #[serde(default)]
    pub occurred_at: Option<u64>,
    #[serde(default)]
    pub request_id: Option<String>,
    #[serde(default)]
    pub call_id: Option<String>,
    #[serde(default)]
    pub payload: Payload,
}

pub fn identifier(s: &str) -> bool {
    !s.trim().is_empty() && s.len() <= 512 && !s.chars().any(char::is_control)
}

impl Event {
    pub fn validate(&self, agent: &str) -> Result<(), String> {
        if self.schema_version != 1 {
            return Err("unsupported_schema".into());
        }
        if self.agent_id != agent
            || !identifier(agent)
            || !identifier(&self.session_id)
            || !identifier(&self.event_id)
        {
            return Err("invalid_identity".into());
        }
        for id in [&self.turn_id, &self.request_id, &self.call_id]
            .into_iter()
            .flatten()
        {
            if !identifier(id) {
                return Err("invalid_correlation_id".into());
            }
        }
        if !matches!(
            self.kind,
            Kind::Discovered
                | Kind::Renamed
                | Kind::Closed
                | Kind::Heartbeat
                | Kind::Test
                | Kind::Submitted
                | Kind::Unassociated
        ) && self.turn_id.is_none()
        {
            return Err("turn_id_required".into());
        }
        if matches!(self.kind, Kind::Requested | Kind::Resolved) && self.request_id.is_none() {
            return Err("request_id_required".into());
        }
        if matches!(self.kind, Kind::ToolStarted | Kind::ToolFinished) && self.call_id.is_none() {
            return Err("call_id_required".into());
        }
        if self.kind == Kind::Requested
            && !matches!(
                self.payload.request_kind,
                Some(
                    crate::domain::WaitingReason::Approval | crate::domain::WaitingReason::Question
                )
            )
        {
            return Err("explicit_request_kind_required".into());
        }
        for s in [
            &self.payload.title,
            &self.payload.project,
            &self.payload.project_path,
            &self.payload.model,
            &self.payload.activity,
        ]
        .into_iter()
        .flatten()
        {
            if s.len() > 2048 || s.chars().any(char::is_control) {
                return Err("invalid_display_field".into());
            }
        }
        if self.occurred_at.is_some_and(|n| n > 253_402_300_799_000) {
            return Err("invalid_timestamp".into());
        }
        Ok(())
    }
}

/// These fields are generated by TaskPulse, never accepted from producer stdin.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Envelope {
    pub version: u8,
    pub source_instance_id: String,
    pub sequence: u64,
    pub journal_epoch: String,
    pub received_at: u64,
    pub adapter_version: String,
    pub evidence: String,
    pub event: Event,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub context: Option<serde_json::Value>,
}
